package main

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
)

var jarpath string
var serverdir string
var ram string

func eulaaccepter(dir string) error {
	eulaPath := filepath.Join(dir, "eula.txt")
	content := []byte("# Generated by MCMAN\neula=true\n")

	return os.WriteFile(eulaPath, content, 0644)
}

func main() {

	fmt.Println("What is your server directory? (use ./ for root dir)")
	fmt.Scan(serverdir)

	fmt.Println("What is the name of your jar file?")
	fmt.Scan(jarpath)

	fmt.Println("How much")
	if err := os.MkdirAll(*&serverdir, 0755); err != nil {
		fmt.Printf("[Error] Failed to create directory: %v\n", err)
		os.Exit(1)
	}

	jarFullPath := filepath.Join(*&serverdir, *&jarpath)
	if _, err := os.Stat(jarFullPath); os.IsNotExist(err) {
		fmt.Printf("[Error] Could not find '%s' in '%s'\n", *&jarpath, *&serverdir)
		os.Exit(1)
	}

	if err := eulaaccepter(*&serverdir); err != nil {
		fmt.Printf("[Warning] Failed to write eula.txt: %v\n", err)
	} else {
		fmt.Println("[Manager] EULA auto-accepted.")
	}

	cmd := exec.Command(
		"java",
		fmt.Sprintf("-Xms%s", ram),
		fmt.Sprintf("-Xmx%s", ram),
		"-jar",
		jarpath,
	)

	cmd.Dir = serverdir
	cmd.Stdin = os.Stdin
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr

	fmt.Println("Starting MC Server")
	if err := cmd.Run(); err != nil {
		fmt.Printf("Server exited with error %v/n", err)
		os.Exit(1)
	}
}
