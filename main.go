package main

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/TwiN/go-choice"
)

type Config struct {
	ServerDir  string   `json:"server_dir"`
	JarFile    string   `json:"jar_file"`
	Ram        string   `json:"ram"`
	UseAikar   bool     `json:"use_aikar"`
	NoGUI      bool     `json:"nogui"`
	ExtraFlags []string `json:"extra_flags"`
}

const configFile = "mcman.json"

var aikarFlags = []string{
	"-XX:+UseG1GC",
	"-XX:+ParallelRefProcEnabled",
	"-XX:MaxGCPauseMillis=200",
	"-XX:+UnlockExperimentalVMOptions",
	"-XX:+DisableExplicitGC",
	"-XX:+AlwaysPreTouch",
	"-XX:G1NewSizePercent=30",
	"-XX:G1MaxNewSizePercent=40",
	"-XX:G1HeapRegionSize=8M",
	"-XX:G1ReservePercent=20",
	"-XX:G1HeapWastePercent=5",
	"-XX:G1MixedGCCountTarget=4",
	"-XX:InitiatingHeapOccupancyPercent=15",
	"-XX:G1MixedGCLiveThresholdPercent=90",
	"-XX:G1RSetUpdatingPauseTimePercent=5",
	"-XX:SurvivorRatio=32",
	"-XX:+PerfDisableSharedMem",
	"-XX:MaxTenuringThreshold=1",
}

func loadConfig() (*Config, error) {
	if _, err := os.Stat(configFile); os.IsNotExist(err) {
		return nil, nil
	}

	data, err := os.ReadFile(configFile)
	if err != nil {
		return nil, err
	}

	var cfg Config
	if err := json.Unmarshal(data, &cfg); err != nil {
		return nil, err
	}

	return &cfg, nil
}

func saveConfig(cfg *Config) error {
	data, err := json.MarshalIndent(cfg, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(configFile, data, 0644)
}

func eulaaccepter(dir string) error {
	eulaPath := filepath.Join(dir, "eula.txt")
	content := []byte("# Generated by MCMAN\neula=true\n")
	return os.WriteFile(eulaPath, content, 0644)
}

func getDirectories() ([]string, error) {
	entries, err := os.ReadDir(".")
	if err != nil {
		return nil, err
	}

	dirs := []string{"./ (Current Directory)"}
	for _, entry := range entries {
		if entry.IsDir() {
			name := entry.Name()
			if strings.HasPrefix(name, ".") {
				continue
			}
			dirs = append(dirs, filepath.Join(".", name))
		}
	}
	return dirs, nil
}

func getJarFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}

	var jars []string
	for _, entry := range entries {
		if !entry.IsDir() && strings.HasSuffix(strings.ToLower(entry.Name()), ".jar") {
			jars = append(jars, entry.Name())
		}
	}
	return jars, nil
}

func runSetupMenu(current *Config) *Config {
	cfg := &Config{
		ServerDir:  ".",
		JarFile:    "server.jar",
		Ram:        "4G",
		UseAikar:   true,
		NoGUI:      true,
		ExtraFlags: []string{},
	}

	if current != nil {
		*cfg = *current
	}

	for {
		aikarStatus := "Disabled"
		if cfg.UseAikar {
			aikarStatus = "Enabled"
		}

		guiStatus := "Disabled"
		if cfg.NoGUI {
			guiStatus = "Enabled"
		}

		options := []string{
			fmt.Sprintf("Server Directory: %s", cfg.ServerDir),
			fmt.Sprintf("Server JAR: %s", cfg.JarFile),
			fmt.Sprintf("RAM: %s", cfg.Ram),
			fmt.Sprintf("Toggle Aikar Optimized JVM Flags (%s)", aikarStatus),
			fmt.Sprintf("Toggle nogui Flag (%s)", guiStatus),
			"Save and Return to Main Menu",
			"Cancel",
		}

		selected, idx, err := gochoice.Pick("Settings & Configuration Menu", options)
		if err != nil || selected == "Cancel" {
			return current
		}

		switch idx {
		case 0:
			dirs, err := getDirectories()
			if err != nil || len(dirs) == 0 {
				fmt.Printf("[Error] Failed to read directories: %v\n", err)
				continue
			}
			pickDir, _, err := gochoice.Pick("Select server directory:", dirs)
			if err == nil {
				if pickDir == "./ (Current Directory)" {
					cfg.ServerDir = "."
				} else {
					cfg.ServerDir = pickDir
				}
			}
		case 1:
			jars, err := getJarFiles(cfg.ServerDir)
			if err != nil || len(jars) == 0 {
				fmt.Printf("[Error] No .jar files found in '%s'\n", cfg.ServerDir)
				continue
			}
			pickJar, _, err := gochoice.Pick("Select server JAR file:", jars)
			if err == nil {
				cfg.JarFile = pickJar
			}
		case 2:
			ramChoices := []string{"1G", "2G", "3G", "4G", "6G", "8G", "10G", "12G", "16G", "24G", "32G"}
			pickRam, _, err := gochoice.Pick("Select RAM allocation:", ramChoices)
			if err == nil {
				cfg.Ram = pickRam
			}
		case 3:
			cfg.UseAikar = !cfg.UseAikar
		case 4:
			cfg.NoGUI = !cfg.NoGUI
		case 5:
			if err := saveConfig(cfg); err != nil {
				fmt.Printf("[Error] Failed to save config: %v\n", err)
			} else {
				fmt.Println("[Manager] Configuration saved to mcman.json")
			}
			return cfg
		}
	}
}

func runServer(cfg *Config) {
	if cfg == nil {
		fmt.Println("[Error] No server configuration found. Run Setup first.")
		return
	}

	if err := os.MkdirAll(cfg.ServerDir, 0755); err != nil {
		fmt.Printf("[Error] Failed to create directory: %v\n", err)
		return
	}

	jarFullPath := filepath.Join(cfg.ServerDir, cfg.JarFile)
	if _, err := os.Stat(jarFullPath); os.IsNotExist(err) {
		fmt.Printf("[Error] Could not find '%s' in '%s'\n", cfg.JarFile, cfg.ServerDir)
		return
	}

	if err := eulaaccepter(cfg.ServerDir); err != nil {
		fmt.Printf("[Warning] Failed to write eula.txt: %v\n", err)
	} else {
		fmt.Println("[Manager] EULA auto-accepted.")
	}

	args := []string{
		fmt.Sprintf("-Xms%s", cfg.Ram),
		fmt.Sprintf("-Xmx%s", cfg.Ram),
	}

	if cfg.UseAikar {
		args = append(args, aikarFlags...)
	}

	if len(cfg.ExtraFlags) > 0 {
		args = append(args, cfg.ExtraFlags...)
	}

	args = append(args, "-jar", cfg.JarFile)

	if cfg.NoGUI {
		args = append(args, "nogui")
	}

	cmd := exec.Command("java", args...)
	cmd.Dir = cfg.ServerDir
	cmd.Stdin = os.Stdin
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr

	fmt.Printf("[Manager] Starting server with command: java %s\n", strings.Join(args, " "))
	if err := cmd.Run(); err != nil {
		fmt.Printf("Server exited with error: %v\n", err)
	}
}

func main() {
	cfg, err := loadConfig()
	if err != nil {
		fmt.Printf("[Warning] Failed to read mcman.json: %v\n", err)
	}

	if cfg == nil {
		fmt.Println("[Manager] No saved config found. Launching initial setup...")
		cfg = runSetupMenu(nil)
		if cfg == nil {
			fmt.Println("[Manager] Setup cancelled. Exiting.")
			os.Exit(0)
		}
	}

	for {
		startLabel := fmt.Sprintf("Start Server (%s / %s / %s)", cfg.ServerDir, cfg.JarFile, cfg.Ram)
		options := []string{
			startLabel,
			"Setup & Flags Configuration",
			"Exit",
		}

		selected, idx, err := gochoice.Pick("Minecraft Server Manager - Main Menu", options)
		if err != nil || idx == 2 || selected == "Exit" {
			fmt.Println("Goodbye.")
			break
		}

		switch idx {
		case 0:
			runServer(cfg)
		case 1:
			updatedCfg := runSetupMenu(cfg)
			if updatedCfg != nil {
				cfg = updatedCfg
			}
		}
	}
}
